export const commands:Command[]=['zoom_in','zoom_out','next_slice','previous_slice','pan_left','pan_right','pan_up','pan_down','reset_view','confirm_pending','pause_control','stop_zoom'];
export const pretty=(s:string)=>{
  if(s==='stop_zoom')return 'Stop zoom';
  if(s==='pause_control')return 'Pause gesture control';
  if(s==='confirm_pending')return 'Confirm pending action';
  return s.replaceAll('_',' ').replace(/^./,c=>c.toUpperCase());
};
